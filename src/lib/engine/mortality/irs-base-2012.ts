/**
 * IRS base mortality tables — Treas. Reg. § 1.430(h)(3)-1(d), Table 2.
 *
 * Source: TD 9983, 88 FR 72357 (October 20, 2023), the final regulations prescribing the mortality
 * tables used under § 430(h)(3)(A). Transcribed mechanically from the Federal Register text at
 * https://www.govinfo.gov/content/pkg/FR-2023-10-20/html/2023-23267.htm. Rates are published to
 * five decimals and stored at that precision.
 *
 * **Base year 2012**, ages 0-120, derived by the IRS from the SOA's Pri-2012 tables. Four rate
 * series — non-annuitant and annuitant, male and female — plus the two **weighting factors** the
 * regulation uses to blend them into a single combined table for small plans.
 *
 * ## Non-annuitant / annuitant, not employee / retiree
 *
 * Per § 1.430(h)(3)-1(b)(4)(i), a non-annuitant is a participant who has not commenced benefits
 * (an active employee or a terminated vested participant) and an annuitant is one who has. The
 * annuitant table also applies to a **beneficiary** of a participant, which is where this table
 * absorbs what the Pri-2012 white collar data splits out as a contingent-survivor basis.
 *
 * ## Two differences from the Pri-2012 white collar table this replaces
 *
 * 1. **Both series run the full 0-120.** The white collar employee series stopped at 80, which
 *    constrained the retirement age to 50-81; these tables tile at every age.
 * 2. **Not white collar.** These are the generally-applicable tables, so they carry no
 *    white-collar adjustment. They are the IRS pairing for the 2024 Adjusted Scale MP-2021, which
 *    is the operator's chosen basis; the white collar table is not.
 *
 * This module is data only — see `irs-static.ts` for the projection to a valuation year.
 */
import type { Gender } from '$lib/domain/insured';

/** The two statuses the regulation's tables distinguish. */
export const IRS_BASES = ['nonAnnuitant', 'annuitant'] as const;
export type IrsBasis = (typeof IRS_BASES)[number];

/** Base year of every rate in this module. */
export const IRS_BASE_YEAR = 2012;
/** First and last age the tables cover. */
export const IRS_BASE_START_AGE = 0;
export const IRS_BASE_END_AGE = 120;

/** One gender's three age-indexed series, each running age 0 to 120. */
export interface IrsBaseSeries {
	/** q(x) for a participant who has not commenced benefits. */
	readonly nonAnnuitant: readonly number[];
	/** q(x) for a participant receiving benefits, and for a beneficiary. */
	readonly annuitant: readonly number[];
	/**
	 * The regulation's small-plan weighting factor, used only to blend the two series into a
	 * combined table: `combined = nonAnnuitant × (1 − w) + annuitant × w`. It stands in for the
	 * chance a participant of that age has commenced benefits, so it is 0 at young ages and 1 once
	 * everyone is assumed retired. A caller that knows a participant's actual status should read the
	 * two series directly and ignore this.
	 */
	readonly weightingFactor: readonly number[];
}

export type IrsBaseTableData = Readonly<Record<Gender, IrsBaseSeries>>;

